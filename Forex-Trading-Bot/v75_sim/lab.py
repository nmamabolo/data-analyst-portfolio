"""Volatility 75 Index: does "sell at RSI 80, buy at 20" work on a market built from random numbers?

Deriv describes the Volatility 75 Index as generated by a cryptographically secure random
number generator with a constant 75% annual volatility and one tick every 2 seconds,
independent of news or any real market. That recipe is a driftless random walk, so this
lab rebuilds it exactly: 2-second ticks, 24/7, assembled into M15 bars. It then runs the
trader's rule and the gold-lab variations on many independent simulated years.

Spread: estimated from the trader's own screenshot (a 0.01-lot sell from 38,912.94 showing
+$0.93 while the bid was 38,797.64 implies an ask near 38,820, i.e. ~22 points or ~0.06%
round trip). Deriv also charges swap on synthetic indices; it is left out here, which only
flatters the rule.

  python -m v75_sim.lab
"""
from pathlib import Path

import numpy as np
import pandas as pd

from gold_rsi.lab import _simulate, signals

RESULTS = Path(__file__).resolve().parent / "results"
ANNUAL_VOL = 0.75
TICK_SECONDS = 2
BAR_SECONDS = 15 * 60
START_PRICE = 38_900.0
SPREAD = 0.00057                    # round-trip cost as a fraction of price (~22 points at 38,900)
YEARS = 20                          # independent simulated years
SEED = 75


def simulate_year(rng: np.random.Generator) -> pd.DataFrame:
    """One year of 2-second ticks (a driftless random walk at 75% volatility) as M15 OHLC bars."""
    ticks_per_bar = BAR_SECONDS // TICK_SECONDS                     # 450
    n_bars = 365 * 24 * 3600 // BAR_SECONDS                         # 35,040 (synthetic indices trade 24/7)
    sigma = ANNUAL_VOL * np.sqrt(TICK_SECONDS / (365 * 24 * 3600))
    steps = rng.normal(-0.5 * sigma ** 2, sigma, size=(n_bars, ticks_per_bar))
    log_path = np.cumsum(steps.ravel()).reshape(n_bars, ticks_per_bar)
    prices = START_PRICE * np.exp(log_path)
    opens = np.concatenate([[START_PRICE], prices[:-1, -1]])
    idx = pd.date_range("2025-01-01", periods=n_bars, freq="15min", tz="UTC")
    return pd.DataFrame({"open": opens, "high": np.maximum(prices.max(axis=1), opens),
                         "low": np.minimum(prices.min(axis=1), opens), "close": prices[:, -1],
                         "segment": 0}, index=idx)


def run_rule(b: pd.DataFrame, entry: str, exit_: str) -> pd.DataFrame:
    el, es, xl, xs, end, stop, target = signals(b, entry, exit_, "none")
    o, h, l, c = (b[x].to_numpy(np.float64) for x in ("open", "high", "low", "close"))
    ent, ext, side, pnl, _ = _simulate(o, h, l, c, el, es, xl, xs, end, stop, target)
    gross = pnl / o[ent]                                            # return per trade
    return pd.DataFrame({"gross": gross, "net": gross - SPREAD, "entry_price": o[ent]})


def main():
    RESULTS.mkdir(exist_ok=True)
    rng = np.random.default_rng(SEED)
    rules = [("touch", "reverse"), ("touch", "rsi_50"), ("touch", "atr_2_2"), ("touch", "atr_2_4"),
             ("confirm", "reverse"), ("confirm", "rsi_50"), ("confirm", "atr_2_2"), ("confirm", "atr_2_4")]
    rows = []
    for year in range(YEARS):
        b = simulate_year(rng)
        for entry, exit_ in rules:
            t = run_rule(b, entry, exit_)
            # Dollars at 0.01 lot: $0.01 per index point, so a trade's $ = return x price x 0.01.
            usd = t.net * t.entry_price * 0.01
            rows.append(dict(year=year, entry=entry, exit=exit_, trades=len(t), win_rate=(t.net > 0).mean(),
                             avg_gross_pct=t.gross.mean() * 100, avg_net_pct=t.net.mean() * 100,
                             year_usd_0p01_lot=usd.sum(), index_move_pct=(b.close.iloc[-1] / START_PRICE - 1) * 100))
    table = pd.DataFrame(rows)
    table.to_csv(RESULTS / "simulated_years.csv", index=False, float_format="%.5f")
    return table


if __name__ == "__main__":
    pd.set_option("display.width", 220)
    t = main()
    s = t.groupby(["entry", "exit"]).agg(trades_per_year=("trades", "mean"), win_rate=("win_rate", "mean"),
                                         avg_gross_pct=("avg_gross_pct", "mean"), avg_net_pct=("avg_net_pct", "mean"),
                                         usd_per_year=("year_usd_0p01_lot", "mean"),
                                         profitable_years=("year_usd_0p01_lot", lambda x: (x > 0).mean()),
                                         best_year=("year_usd_0p01_lot", "max"), worst_year=("year_usd_0p01_lot", "min"))
    print(s.round(3).to_string())
